import type { Dataset } from '../types'
import { fmtInt, fmtNum } from '../format'

export function Method({ ds }: { ds: Dataset }) {
  const q = ds.meta.quotes
  const p = ds.meta.params
  const o = ds.meta.x5_stores_official
  const osmTotal = ds.regions.reduce((s, r) => s + r.stores_osm.pyaterochka + r.stores_osm.perekrestok + r.stores_osm.chizhik, 0)
  return (
    <div className="method">
      <div className="method-cols">
        <section>
          <h3>Что показывает карта</h3>
          <p>
            <b>Разрыв</b> сравнивает, сколько килограммов помощи в год приходится на одного малоимущего в регионе, со средним по стране. Значение 1 означает
            «как в среднем», 0,25 означает в четыре раза меньше.
          </p>
          <p>
            Пока фонд не загрузил свою выгрузку, помощь по регионам оценивается моделью: общий объём ({fmtInt(p.baseline_tonnes)} т в год, итоги «Пятёрочки» за
            2024 год) раскладывается пропорционально числу магазинов X5. Так устроен сбор: продукты покупатели оставляют в магазинах, а платформа фонда
            позволяет «направлять помощь точечно в те регионы, где она была собрана».
          </p>
          <h3>Как считается эффект</h3>
          <p>
            Исследование фонда «Выручаем» и экономического факультета МГУ (данные Росстата по 81 региону за 30 лет): «{q.msu.text}». Мы используем этот
            коэффициент как полуэластичность: число малоимущих × (1 − e<sup>−{fmtNum(p.msu_coef, 4)} × кг на душу</sup>). На реальных объёмах это почти
            линейно: один килограмм даёт эффект, пропорциональный доле бедных в регионе.
          </p>
          <p>
            Это статистическая связь, а не обещание: она учитывает «прочие равные», но не доказывает причинность. Поэтому числа людей годятся, чтобы
            сравнивать варианты между собой, а не для отчёта о результате.
          </p>
          <h3>Способы распределения</h3>
          <ul>
            <li><b>Как сейчас</b>: пропорционально магазинам X5 (или вашей выгрузке).</li>
            <li><b>По нужде</b>: каждому малоимущему поровну килограммов.</li>
            <li><b>Закрыть разрыв</b>: деньги получают регионы с наименьшим числом кг на малоимущего, пока они не догонят следующих.</li>
          </ul>
          <p>
            Рубли переводятся в килограммы по цене {fmtInt(p.price_per_kg)} ₽ за кг («Перекрёсток»: 52 т продуктов на сумму около 12 млн ₽), умноженной на
            региональный индекс стоимости минимального набора продуктов.
          </p>
        </section>
        <section>
          <h3>Данные</h3>
          <ul className="sources">
            <li>
              Уровень бедности по субъектам, {ds.meta.years.poverty}: Росстат,{' '}
              <a href="https://fedstat.ru/indicator/62063" target="_blank" rel="noreferrer">ЕМИСС, показатель 62063</a>.
            </li>
            <li>
              Численность населения, {ds.meta.years.population}: Росстат,{' '}
              <a href="https://fedstat.ru/indicator/31556" target="_blank" rel="noreferrer">ЕМИСС, 31556</a>.
            </li>
            <li>
              Стоимость минимального набора продуктов, {ds.meta.years.basket}: Росстат,{' '}
              <a href="https://fedstat.ru/indicator/31481" target="_blank" rel="noreferrer">ЕМИСС, 31481</a>.
            </li>
            <li>
              Магазины X5: {fmtInt(osmTotal)} точек «Пятёрочки», «Перекрёстка» и «Чижика» с координатами из{' '}
              <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noreferrer">OpenStreetMap</a> ({ds.meta.osm.fetched_at}), по границам
              регионов geoBoundaries. Число по каждой сети пересчитано на официальный итог X5 на 31.12.2025: {fmtInt(o.pyaterochka)}, {fmtInt(o.perekrestok)} и{' '}
              {fmtInt(o.chizhik)} (<a href={q.x5_stores.url} target="_blank" rel="noreferrer">источник</a>).
            </li>
            <li>
              Исследование фонда и МГУ, оценка роста без НДС: <a href={q.msu.url} target="_blank" rel="noreferrer">пресс-релиз фонда</a>.
            </li>
            <li>
              Объём помощи 2024 года: <a href={q.volume_2024.url} target="_blank" rel="noreferrer">итоги «Пятёрочки»</a>; цена килограмма:{' '}
              <a href={q.price_kg.url} target="_blank" rel="noreferrer">итоги «Перекрёстка»</a>; региональные факты: пресс-релизы о «Корзине доброты» и
              фудшеринге (ссылки в карточках регионов).
            </li>
          </ul>
          <h3>Ограничения</h3>
          <ul>
            <li>
              Росстат публикует уровень бедности по {ds.regions.length} субъектам, без учёта новых субъектов (ДНР, ЛНР, Запорожской и Херсонской областей).
              Карта показывает эти {ds.regions.length}.
            </li>
            <li>OpenStreetMap неполон: модель использует долю региона, а не абсолютное число магазинов, и пересчитывает её на официальный итог.</li>
            <li>Модель «помощь там, где магазины» заменяется фактом, как только фонд загружает выгрузку платформы.</li>
            <li>Население взято за {ds.meta.years.population}, бедность за {ds.meta.years.poverty}: число малоимущих в регионе — оценка.</li>
          </ul>
          <p className="muted small">Данные собраны {ds.meta.built_at}. Скрипты сборки и сырые ответы ЕМИСС лежат в репозитории, всё воспроизводится одной командой.</p>
        </section>
      </div>
    </div>
  )
}
