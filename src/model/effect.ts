import type { Region } from '../types'

/**
 * Ожидаемое снижение числа малоимущих при дополнительных kg кг помощи в год.
 * Исследование фонда «Выручаем» и МГУ (2026): +1 кг на душу в год связан со снижением уровня бедности на 20,55 %
 * при прочих равных. Трактуем как полуэластичность: бедность × exp(−coef × кг на душу).
 * Это статистическая связь, а не гарантированный эффект: годится для сравнения вариантов между собой.
 */
export function lifted(r: Region, kg: number, coef: number): number {
  if (kg <= 0 || r.population <= 0) return 0
  return r.poor * (1 - Math.exp((-coef * kg) / r.population))
}
